def compile_demand_notebook():
    nb = new_notebook()
    nb.cells.append(new_markdown_cell(SUPERSEDED_NOTE))
    
    nb.cells.append(new_markdown_cell("# Phase 6: Customer Demand Prediction\nThis notebook builds and compares predictive ML models (Linear Regression vs. Random Forest Regressor) to estimate expected hourly demand for shops."))
    
    # Imports
    nb.cells.append(new_code_cell("""import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import pickle
import os

sns.set_theme(style="whitegrid")
os.makedirs('../models', exist_ok=True)
print("Libraries loaded.")"""))
    
    # Load and Prepare Data
    nb.cells.append(new_markdown_cell("## 1. Load Data and Aggregate to Hourly Demand\nWe aggregate visits into shop-date-hour count to form the target variable `customer_count`."))
    nb.cells.append(new_code_cell("""visits = pd.read_csv('../data/processed/visits.csv')
shops = pd.read_csv('../data/processed/shops.csv')

# Extract hour and day features
visits['arrival_datetime'] = pd.to_datetime(visits['date'] + ' ' + visits['arrival_time'])
visits['hour'] = visits['arrival_datetime'].dt.hour
visits['day_of_week'] = visits['arrival_datetime'].dt.dayofweek
visits['month'] = visits['arrival_datetime'].dt.month

# Group by shop, date, hour to get client counts (demand)
demand = visits.groupby(['shop_id', 'date', 'hour']).size().reset_index(name='customer_count')

# Pivot/fill missing combinations with 0 to represent 0 demand hours
# Let's generate a full index of shops, dates, and hours (e.g. from 8 AM to 8 PM)
all_shops = shops['shop_id'].unique()
all_dates = visits['date'].unique()
all_hours = np.arange(8, 21) # 8 AM to 8 PM

index = pd.MultiIndex.from_product([all_shops, all_dates, all_hours], names=['shop_id', 'date', 'hour'])
full_df = pd.DataFrame(index=index).reset_index()

demand = pd.merge(full_df, demand, on=['shop_id', 'date', 'hour'], how='left').fillna(0)
demand['customer_count'] = demand['customer_count'].astype(int)
print(f"Total rows in aggregated demand matrix: {len(demand)}")"""))
    
    # Merge features
    nb.cells.append(new_markdown_cell("## 2. Feature Engineering\nMerge shop metadata and time-based features."))
    nb.cells.append(new_code_cell("""demand = demand.merge(shops[['shop_id', 'rating', 'number_of_seats', 'number_of_barbers', 'shop_type']], on='shop_id')

demand['date'] = pd.to_datetime(demand['date'])
demand['day_of_week'] = demand['date'].dt.dayofweek
demand['weekend_flag'] = (demand['day_of_week'] >= 4).astype(int) # Friday, Saturday, Sunday
demand['month'] = demand['date'].dt.month

# Add a simple historical demand average for each (shop_id, hour, day_of_week) as a feature
hist_demand = demand.groupby(['shop_id', 'hour', 'day_of_week'])['customer_count'].mean().reset_index(name='historical_average_demand')
demand = demand.merge(hist_demand, on=['shop_id', 'hour', 'day_of_week'], how='left')

# Drop non-feature columns
X_cols = ['hour', 'day_of_week', 'weekend_flag', 'month', 'rating', 'number_of_seats', 'number_of_barbers', 'historical_average_demand']
X = demand[X_cols]
y = demand['customer_count']

# Categorical conversion if any (shop_type is ignored for now to keep features simple)
print("Features prepared.")"""))

    # Train test split
    nb.cells.append(new_markdown_cell("## 3. Time-Based Train/Test Split\nTo avoid data leakage, we split training and testing by date (first 75 days for train, last 15 days for test)."))
    nb.cells.append(new_code_cell("""# Date threshold split
unique_dates = sorted(demand['date'].unique())
split_idx = int(len(unique_dates) * 0.8)
split_date = unique_dates[split_idx]

train_mask = demand['date'] < split_date
test_mask = demand['date'] >= split_date

X_train, X_test = X[train_mask], X[test_mask]
y_train, y_test = y[train_mask], y[test_mask]

print(f"Train size: {len(X_train)}, Test size: {len(X_test)}")
print(f"Split date threshold: {split_date}")"""))

    # Models Comparison
    nb.cells.append(new_markdown_cell("## 4. Train Models & Compare"))
    nb.cells.append(new_code_cell("""lr = LinearRegression()
lr.fit(X_train, y_train)
lr_preds = lr.predict(X_test)

rf = RandomForestRegressor(n_estimators=100, max_depth=10, random_state=42)
rf.fit(X_train, y_train)
rf_preds = rf.predict(X_test)

# Metrics
print("Linear Regression:")
print(f" - MAE: {mean_absolute_error(y_test, lr_preds):.3f}")
print(f" - RMSE: {np.sqrt(mean_squared_error(y_test, lr_preds)):.3f}")
print(f" - R2: {r2_score(y_test, lr_preds):.3f}")

print("\\nRandom Forest:")
print(f" - MAE: {mean_absolute_error(y_test, rf_preds):.3f}")
print(f" - RMSE: {np.sqrt(mean_squared_error(y_test, rf_preds)):.3f}")
print(f" - R2: {r2_score(y_test, rf_preds):.3f}")"""))

    # Feature Importance
    nb.cells.append(new_markdown_cell("## 5. Feature Importance\nPlotting feature importance for the Random Forest model."))
    nb.cells.append(new_code_cell("""importances = rf.feature_importances_
indices = np.argsort(importances)[::-1]

plt.figure(figsize=(10, 5))
sns.barplot(x=importances[indices], y=[X_cols[i] for i in indices], palette="viridis")
plt.title("Feature Importance - Demand Prediction")
plt.xlabel("Importance score")
plt.ylabel("Features")
plt.savefig('../reports/figures/demand_feature_importance.png')
plt.show()"""))

    # Save best model
    nb.cells.append(new_markdown_cell("## 6. Save Model\nSaving the best performing model (Random Forest) as a pickle file."))
    nb.cells.append(new_code_cell("""with open('../models/demand_model.pkl', 'wb') as f:
    pickle.dump(rf, f)
print("Saved demand_model.pkl successfully.")"""))

    return nb

def compile_waiting_notebook():
    nb = new_notebook()
    nb.cells.append(new_markdown_cell(SUPERSEDED_NOTE))
    
    nb.cells.append(new_markdown_cell("# Phase 6: Waiting Time & No-Show Predictions\nThis notebook trains and evaluates a Random Forest Regressor to predict customer waiting time in minutes, and a Logistic Regression classifier to predict the no-show probability of appointments."))
    
    # Imports
    nb.cells.append(new_code_cell("""import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score, accuracy_score, classification_report
import pickle
import os

print("Libraries loaded.")"""))
    
    # Load data
    nb.cells.append(new_markdown_cell("## 1. Load Data"))
    nb.cells.append(new_code_cell("""visits = pd.read_csv('../data/processed/visits.csv')
shops = pd.read_csv('../data/processed/shops.csv')
appointments = pd.read_csv('../data/processed/appointments.csv')
customers = pd.read_csv('../data/processed/customers.csv')"""))

    # Predict Waiting Time
    nb.cells.append(new_markdown_cell("## 2. Prepare Data for Waiting Time Prediction\nWe merge features such as queue length, occupied seats, and shop capacity from availability and visits tables."))
    nb.cells.append(new_code_cell("""# In visits: we have arrival_time (HH:MM) and date
# We will match the closest availability log at that date & hour to capture queue state.
visits['hour'] = pd.to_datetime(visits['arrival_time']).dt.hour
visits['day_of_week'] = pd.to_datetime(visits['date']).dt.dayofweek

# Clean availability timestamps to extract hour and date
availability = pd.read_csv('../data/processed/availability.csv')
availability['timestamp_dt'] = pd.to_datetime(availability['timestamp'])
availability['date_str'] = availability['timestamp_dt'].dt.strftime('%Y-%m-%d')
availability['hour'] = availability['timestamp_dt'].dt.hour

# Join visits with availability on (shop_id, date, hour)
# To avoid double joins, let's keep only unique availability rows
avail_unique = availability.drop_duplicates(subset=['shop_id', 'date_str', 'hour'])

wt_df = visits.merge(avail_unique[['shop_id', 'date_str', 'hour', 'queue_length', 'occupied_seats', 'available_seats']], 
                     left_on=['shop_id', 'date', 'hour'], 
                     right_on=['shop_id', 'date_str', 'hour'], 
                     how='left')

# Drop null joins (hours outside standard snapshots) and fillna
wt_df['queue_length'] = wt_df['queue_length'].fillna(0)
wt_df['occupied_seats'] = wt_df['occupied_seats'].fillna(0)
wt_df['available_seats'] = wt_df['available_seats'].fillna(wt_df['seat_id'])

# Add shop metrics
wt_df = wt_df.merge(shops[['shop_id', 'number_of_barbers', 'number_of_seats']], on='shop_id')

wt_cols = ['queue_length', 'occupied_seats', 'available_seats', 'number_of_barbers', 'number_of_seats', 'hour', 'day_of_week']
X_wt = wt_df[wt_cols]
y_wt = wt_df['waiting_time_minutes']

print(f"Features: {wt_cols}")
print(f"Total rows: {len(X_wt)}")"""))

    # Train Wait Time model
    nb.cells.append(new_markdown_cell("## 3. Train Waiting Time Model (Random Forest)"))
    nb.cells.append(new_code_cell("""X_train_wt, X_test_wt, y_train_wt, y_test_wt = train_test_split(X_wt, y_wt, test_size=0.2, random_state=42)

rf_wt = RandomForestRegressor(n_estimators=100, max_depth=10, random_state=42)
rf_wt.fit(X_train_wt, y_train_wt)
wt_preds = rf_wt.predict(X_test_wt)

print("Waiting Time Predictor Metrics:")
print(f" - MAE: {mean_absolute_error(y_test_wt, wt_preds):.3f} minutes")
print(f" - RMSE: {np.sqrt(mean_squared_error(y_test_wt, wt_preds)):.3f}")
print(f" - R2: {r2_score(y_test_wt, wt_preds):.3f}")

# Save wait time model
with open('../models/waiting_time_model.pkl', 'wb') as f:
    pickle.dump(rf_wt, f)
print("Saved waiting_time_model.pkl successfully.")"""))

    # Predict No-Shows
    nb.cells.append(new_markdown_cell("## 4. Appointment No-Show Prediction (Classification)\nGoal: Predict `no_show_flag` utilizing Logistic Regression."))
    nb.cells.append(new_code_cell("""# Merge customer demographics and appointment parameters
app_df = appointments.merge(customers[['customer_id', 'age_group', 'gender', 'customer_rating']], on='customer_id')

# Encode categorical values
app_df['gender_Male'] = (app_df['gender'] == 'Male').astype(int)
app_df['gender_Female'] = (app_df['gender'] == 'Female').astype(int)

# Encode age groups
for age in ['18-25', '26-35', '36-45', '46-60', '60+']:
    app_df[f'age_{age}'] = (app_df['age_group'] == age).astype(int)

# Extract hour of appointment
app_df['hour'] = pd.to_datetime(app_df['appointment_time']).dt.hour

# Calculate booking lag (days between booking and appointment)
app_df['booking_dt'] = pd.to_datetime(app_df['booking_time'])
app_df['app_dt'] = pd.to_datetime(app_df['appointment_date'] + ' ' + app_df['appointment_time'])
app_df['booking_lag_days'] = (app_df['app_dt'] - app_df['booking_dt']).dt.total_seconds() / (24 * 3600)

no_show_cols = ['gender_Male', 'gender_Female', 'age_18-25', 'age_26-35', 'age_36-45', 'age_46-60', 'age_60+', 'hour', 'customer_rating', 'booking_lag_days']
X_ns = app_df[no_show_cols]
y_ns = app_df['no_show_flag']

print(f"No-show features: {no_show_cols}")
print(f"Target count: {y_ns.value_counts()}")"""))

    # Train Logistic Regression for no-show
    nb.cells.append(new_markdown_cell("## 5. Train No-Show Classifier"))
    nb.cells.append(new_code_cell("""X_train_ns, X_test_ns, y_train_ns, y_test_ns = train_test_split(X_ns, y_ns, test_size=0.2, random_state=42, stratify=y_ns)

lr_ns = LogisticRegression(class_weight='balanced', max_iter=1000, random_state=42)
lr_ns.fit(X_train_ns, y_train_ns)
ns_preds = lr_ns.predict(X_test_ns)

print("No-Show Classifier Performance:")
print(f"Accuracy: {accuracy_score(y_test_ns, ns_preds):.3f}")
print("\\nClassification Report:")
print(classification_report(y_test_ns, ns_preds))

with open('../models/noshow_model.pkl', 'wb') as f:
    pickle.dump(lr_ns, f)
print("Saved noshow_model.pkl successfully.")"""))

    return nb

def execute_and_save_notebook(nb, path):
    print(f"Compiling {path}...")
    with open(path, 'w', encoding='utf-8') as f:
        nbformat.write(nb, f)
        
    print(f"Executing {path}...")
    ep = ExecutePreprocessor(timeout=600, kernel_name='python3')
    
    # We must run the notebook inside its parent directory to keep relative paths correct
    notebook_dir = os.path.dirname(path)
    try:
        ep.preprocess(nb, {'metadata': {'path': notebook_dir}})
        print(f"Successfully executed {path}.")
    except Exception as e:
        print(f"Error executing {path}: {str(e)}")
        
    with open(path, 'w', encoding='utf-8') as f:
        nbformat.write(nb, f)

