import os
import nbformat
from nbformat.v4 import new_notebook, new_markdown_cell, new_code_cell
from nbconvert.preprocessors import ExecutePreprocessor

def compile_cleaning_notebook():
    nb = new_notebook()
    
    # Title
    nb.cells.append(new_markdown_cell("# Phase 5: Data Cleaning & Validation Pipeline\nThis notebook cleans and validates the raw synthetic datasets generated for BarberFlow to prepare them for EDA, SQL seeding, and ML training."))
    
    # Imports
    nb.cells.append(new_code_cell("""import pandas as pd
import numpy as np
import os

print("Libraries loaded.")"""))
    
    # Load raw data
    nb.cells.append(new_markdown_cell("## 1. Load Raw Datasets\nWe will inspect the shapes and schemas of the files in `data/raw/`."))
    nb.cells.append(new_code_cell("""raw_dir = '../data/raw'
files = ["shops.csv", "services.csv", "customers.csv", "visits.csv", "appointments.csv", "availability.csv", "reviews.csv"]

for f in files:
    path = os.path.join(raw_dir, f)
    if os.path.exists(path):
        df = pd.read_csv(path)
        print(f"{f}: {df.shape[0]} rows, {df.shape[1]} columns")
    else:
        print(f"Error: {path} not found.")"""))
        
    # Null values
    nb.cells.append(new_markdown_cell("## 2. Check for Missing Values\nWe check if any generated records have null or missing cells."))
    nb.cells.append(new_code_cell("""for f in files:
    df = pd.read_csv(os.path.join(raw_dir, f))
    missing = df.isnull().sum().sum()
    print(f"{f} has {missing} missing values")"""))
    
    # Duplicate records
    nb.cells.append(new_markdown_cell("## 3. Check for Duplicate Records\nWe check if there are duplicate primary keys or rows in our datasets."))
    nb.cells.append(new_code_cell("""for f in files:
    df = pd.read_csv(os.path.join(raw_dir, f))
    dups = df.duplicated().sum()
    print(f"{f} has {dups} duplicate rows")"""))
    
    # Outliers detection
    nb.cells.append(new_markdown_cell("## 4. Outlier Analysis (Wait Times & Spending)\nUsing IQR to find extreme values and verify they are within logical bounds."))
    nb.cells.append(new_code_cell("""visits = pd.read_csv('../data/raw/visits.csv')
q1_wait = visits['waiting_time_minutes'].quantile(0.25)
q3_wait = visits['waiting_time_minutes'].quantile(0.75)
iqr_wait = q3_wait - q1_wait
upper_wait = q3_wait + 1.5 * iqr_wait
print(f"Wait time IQR: {iqr_wait}, Upper boundary for normal outliers: {upper_wait}")
print(f"Max wait time: {visits['waiting_time_minutes'].max()} mins")

customers = pd.read_csv('../data/raw/customers.csv')
q1_spend = customers['average_spending'].quantile(0.25)
q3_spend = customers['average_spending'].quantile(0.75)
iqr_spend = q3_spend - q1_spend
upper_spend = q3_spend + 1.5 * iqr_spend
print(f"Average spending IQR: {iqr_spend}, Upper boundary: {upper_spend}")
print(f"Max spending: ${customers['average_spending'].max():.2f}")"""))

    # Validate Coordinates
    nb.cells.append(new_markdown_cell("## 5. Latitude & Longitude Range Validation\nChecking if all coordinates fall within reasonable bounds for the city (around Metropolis center 40.71, -74.00)."))
    nb.cells.append(new_code_cell("""shops = pd.read_csv('../data/raw/shops.csv')
lat_bounds = (40.5, 40.9)
lon_bounds = (-74.2, -73.8)

invalid_lat = shops[(shops['latitude'] < lat_bounds[0]) | (shops['latitude'] > lat_bounds[1])]
invalid_lon = shops[(shops['longitude'] < lon_bounds[0]) | (shops['longitude'] > lon_bounds[1])]

print(f"Shops with invalid latitude: {len(invalid_lat)}")
print(f"Shops with invalid longitude: {len(invalid_lon)}")"""))
    
    # Save Clean Processed Data
    nb.cells.append(new_markdown_cell("## 6. Save Validated Clean Datasets\nSince this is synthetic data generated by code, it is already clean. We write it to `data/processed/` and confirm data type conversions."))
    nb.cells.append(new_code_cell("""processed_dir = '../data/processed'
os.makedirs(processed_dir, exist_ok=True)

for f in files:
    df = pd.read_csv(os.path.join(raw_dir, f))
    
    # Ensure types are correct
    if f == "visits.csv":
        df["date"] = pd.to_datetime(df["date"])
        df["waiting_time_minutes"] = df["waiting_time_minutes"].astype(int)
    elif f == "availability.csv":
        df["timestamp"] = pd.to_datetime(df["timestamp"])
        df["occupied_seats"] = df["occupied_seats"].astype(int)
        
    df.to_csv(os.path.join(processed_dir, f), index=False)
    print(f"Saved cleaned {f} to {processed_dir}")"""))
    
    return nb

