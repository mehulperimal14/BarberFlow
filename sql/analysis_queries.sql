-- BarberFlow analytical queries demonstrating SQL skills (CTEs, Window functions, Aggregations, Joins)
-- All 20 queries run on the SQLite database built by scripts/seed_db.py (verified by tests/test_sql_queries.py).

-- 1. Top-Rated Barber Shops
-- Business Value: Identifies premier shops to featured in recommendations.
SELECT 
    shop_id, 
    shop_name, 
    area, 
    rating, 
    review_count
FROM shops
WHERE shop_status = 'Active'
ORDER BY rating DESC, review_count DESC
LIMIT 10;


-- 2. Cheapest Shops (Affordability Analysis)
-- Business Value: Shows average pricing by shop to target price-sensitive customers.
SELECT 
    s.shop_id,
    s.shop_name,
    s.area,
    ROUND(AVG(srv.price), 2) AS average_price
FROM shops s
JOIN services srv ON s.shop_id = srv.shop_id
GROUP BY s.shop_id, s.shop_name, s.area
ORDER BY average_price ASC
LIMIT 10;


-- 3. Shops with Shortest Average Waiting Time
-- Business Value: Highlights highly efficient shops or low demand shops.
SELECT 
    s.shop_id,
    s.shop_name,
    s.number_of_barbers,
    ROUND(AVG(v.waiting_time_minutes), 1) AS avg_wait_time
FROM shops s
JOIN visits v ON s.shop_id = v.shop_id
GROUP BY s.shop_id, s.shop_name, s.number_of_barbers
ORDER BY avg_wait_time ASC
LIMIT 10;


-- 4. Peak Demand Hours (Market-wide)
-- Business Value: Informs staffing needs and promotional schedules by hour.
SELECT 
    STRFTIME('%H', arrival_time || ':00') AS arrival_hour,
    COUNT(*) AS total_visits,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM visits), 2) AS percentage_of_total
FROM visits
GROUP BY arrival_hour
ORDER BY total_visits DESC;


-- 5. Peak Demand Days (Weekday Analysis)
-- Business Value: Helps schedule promotions during slow days and adjust staffing on weekends.
SELECT 
    CASE CAST(STRFTIME('%w', date) AS INTEGER)
        WHEN 0 THEN 'Sunday'
        WHEN 1 THEN 'Monday'
        WHEN 2 THEN 'Tuesday'
        WHEN 3 THEN 'Wednesday'
        WHEN 4 THEN 'Thursday'
        WHEN 5 THEN 'Friday'
        WHEN 6 THEN 'Saturday'
    END AS day_of_week,
    COUNT(*) AS total_visits,
    ROUND(AVG(waiting_time_minutes), 1) AS avg_wait_time
FROM visits
GROUP BY day_of_week, CAST(STRFTIME('%w', date) AS INTEGER)
ORDER BY total_visits DESC;


-- 6. Average Waiting Time by Shop (Ranked)
-- Business Value: Ranks shops by customer wait times using a Window Function.
SELECT 
    s.shop_id,
    s.shop_name,
    ROUND(AVG(v.waiting_time_minutes), 1) AS avg_wait_minutes,
    RANK() OVER (ORDER BY AVG(v.waiting_time_minutes) DESC) AS wait_rank_worst_to_best
FROM shops s
JOIN visits v ON s.shop_id = v.shop_id
GROUP BY s.shop_id, s.shop_name;


-- 7. Average Service Duration by Service Type
-- Business Value: Understands time blocks required per service to improve reservation planning.
SELECT 
    service_name,
    ROUND(AVG(service_duration_minutes), 1) AS avg_duration_minutes,
    COUNT(*) AS total_completed
FROM visits v
JOIN services s ON v.service_id = s.service_id
GROUP BY service_name
ORDER BY avg_duration_minutes DESC;


-- 8. Total Revenue generated by each Shop
-- Business Value: Measures financial performance and ranks shops by raw sales.
SELECT 
    s.shop_id,
    s.shop_name,
    s.shop_type,
    ROUND(SUM(srv.price), 2) AS total_revenue,
    COUNT(v.visit_id) AS total_visits,
    ROUND(SUM(srv.price) / COUNT(v.visit_id), 2) AS avg_ticket_size
FROM shops s
JOIN visits v ON s.shop_id = v.shop_id
JOIN services srv ON v.service_id = srv.service_id
GROUP BY s.shop_id, s.shop_name, s.shop_type
ORDER BY total_revenue DESC;


-- 9. Revenue by Service Category
-- Business Value: Identifies the highest-grossing services to optimize marketing.
SELECT 
    srv.service_name,
    COUNT(v.visit_id) AS total_sold,
    ROUND(SUM(srv.price), 2) AS total_revenue,
    ROUND(SUM(srv.price) * 100.0 / (
        SELECT SUM(s2.price) 
        FROM visits v2 
        JOIN services s2 ON v2.service_id = s2.service_id
    ), 2) AS revenue_share_percentage
FROM visits v
JOIN services srv ON v.service_id = srv.service_id
GROUP BY srv.service_name
ORDER BY total_revenue DESC;


-- 10. Capacity Utilization by Shop
-- Business Value: Calculates how much seat capacity is utilized. 
-- Utilization % = (Occupied Seats / Total Seats) * 100
SELECT 
    s.shop_id,
    s.shop_name,
    s.number_of_seats,
    ROUND(AVG(a.occupied_seats) * 100.0 / s.number_of_seats, 2) AS average_utilization_pct
FROM shops s
JOIN availability a ON s.shop_id = a.shop_id
GROUP BY s.shop_id, s.shop_name, s.number_of_seats
ORDER BY average_utilization_pct DESC;


-- 11. Bottleneck Shops: High Demand but Low Capacity
-- Business Value: Identifies shops that are losing business because they don't have enough barbers/seats.
WITH ShopVisits AS (
    SELECT shop_id, COUNT(*) AS visits_count, AVG(waiting_time_minutes) AS avg_wait
    FROM visits
    GROUP BY shop_id
)
SELECT 
    s.shop_id,
    s.shop_name,
    s.number_of_seats,
    s.number_of_barbers,
    sv.visits_count,
    ROUND(sv.avg_wait, 1) AS avg_wait_time
FROM shops s
JOIN ShopVisits sv ON s.shop_id = sv.shop_id
WHERE s.number_of_seats <= 3 AND sv.visits_count > (
    SELECT AVG(visits_count) FROM ShopVisits
)
ORDER BY sv.visits_count DESC;


-- 12. Underutilized Shops with Excess Capacity
-- Business Value: Flags shops with 5+ seats but low average utilization (<40%). Excellent candidates for discount campaigns.
WITH ShopUtilization AS (
    SELECT 
        shop_id,
        ROUND(AVG(occupied_seats) * 100.0 / total_seats, 2) AS util_pct
    FROM availability
    GROUP BY shop_id
)
SELECT 
    s.shop_id,
    s.shop_name,
    s.number_of_seats,
    su.util_pct AS avg_utilization_pct
FROM shops s
JOIN ShopUtilization su ON s.shop_id = su.shop_id
WHERE s.number_of_seats >= 5 AND su.util_pct < 40.0
ORDER BY avg_utilization_pct ASC;


-- 13. Loyal Customers: Frequent Visits Analysis
-- Business Value: Finds repeat customers for loyalty reward programs.
SELECT 
    c.customer_id,
    c.age_group,
    c.gender,
    COUNT(v.visit_id) AS total_visits,
    ROUND(SUM(srv.price), 2) AS total_spent
FROM customers c
JOIN visits v ON c.customer_id = v.customer_id
JOIN services srv ON v.service_id = srv.service_id
GROUP BY c.customer_id, c.age_group, c.gender
HAVING total_visits >= 12
ORDER BY total_visits DESC
LIMIT 15;


-- 14. Appointment Cancellation Rate by Shop
-- Business Value: Identifies cancellation trends and shops suffering from lost appointment slots.
SELECT 
    s.shop_id,
    s.shop_name,
    COUNT(a.appointment_id) AS total_appointments,
    SUM(CASE WHEN a.status = 'Cancelled' THEN 1 ELSE 0 END) AS cancelled_count,
    ROUND(SUM(CASE WHEN a.status = 'Cancelled' THEN 1 ELSE 0 END) * 100.0 / COUNT(a.appointment_id), 2) AS cancellation_rate_pct
FROM shops s
JOIN appointments a ON s.shop_id = a.shop_id
GROUP BY s.shop_id, s.shop_name
ORDER BY cancellation_rate_pct DESC;


-- 15. No-Show Rate by Customer Segment
-- Business Value: Shows which demographic is most likely to no-show, allowing tailored reminders.
SELECT 
    c.age_group,
    c.gender,
    COUNT(a.appointment_id) AS total_appointments,
    SUM(a.no_show_flag) AS no_shows,
    ROUND(SUM(a.no_show_flag) * 100.0 / COUNT(a.appointment_id), 2) AS no_show_rate_pct
FROM customers c
JOIN appointments a ON c.customer_id = a.customer_id
GROUP BY c.age_group, c.gender
ORDER BY no_show_rate_pct DESC;


-- 16. Customer Rating vs. Waiting Time Analysis
-- Business Value: Validates the hypothesis that longer waiting times hurt ratings.
-- Reviews have no visit_id, so each review is matched to the reviewer's visit at the same shop on the
-- review date or the day before, keeping exactly ONE visit per review (avoids join fan-out).
WITH matched AS (
    SELECT r.review_id, r.rating, r.waiting_time_rating, v.waiting_time_minutes,
           ROW_NUMBER() OVER (PARTITION BY r.review_id ORDER BY v.date DESC, v.visit_id DESC) AS rn
    FROM reviews r
    JOIN visits v ON v.customer_id = r.customer_id AND v.shop_id = r.shop_id
                 AND v.date BETWEEN DATE(r.review_date, '-1 day') AND r.review_date
)
SELECT 
    CASE 
        WHEN waiting_time_minutes = 0 THEN '0 min (No Wait)'
        WHEN waiting_time_minutes <= 10 THEN '1-10 min (Short)'
        WHEN waiting_time_minutes <= 25 THEN '11-25 min (Medium)'
        ELSE '25+ min (Long Wait)'
    END AS wait_time_tier,
    COUNT(*) AS total_reviews,
    ROUND(AVG(rating), 2) AS avg_customer_rating,
    ROUND(AVG(waiting_time_rating), 2) AS avg_wait_experience_rating
FROM matched
WHERE rn = 1
GROUP BY wait_time_tier
ORDER BY avg_customer_rating DESC;


-- 17. Average Price of Service Categories by Area
-- Business Value: Helps owners benchmark prices in their specific local market.
SELECT 
    s.area,
    srv.service_name,
    ROUND(AVG(srv.price), 2) AS avg_price,
    MIN(srv.price) AS min_price,
    MAX(srv.price) AS max_price
FROM shops s
JOIN services srv ON s.shop_id = srv.shop_id
GROUP BY s.area, srv.service_name
ORDER BY s.area, avg_price DESC;


-- 18. Most Popular Services (Volume vs. Margin)
-- Business Value: Guides services bundle strategy and resource allocation.
SELECT 
    srv.service_name,
    COUNT(v.visit_id) AS visit_count,
    ROUND(AVG(srv.price), 2) AS average_price,
    ROUND(SUM(srv.price), 2) AS gross_revenue
FROM visits v
JOIN services srv ON v.service_id = srv.service_id
GROUP BY srv.service_name
ORDER BY visit_count DESC;


-- 19. Weekend vs. Weekday Demand Comparison (by Shop Type)
-- Business Value: Shows how different categories of shops respond to the weekend.
SELECT 
    s.shop_type,
    SUM(CASE WHEN STRFTIME('%w', v.date) IN ('5', '6', '0') THEN 1 ELSE 0 END) AS weekend_visits,
    SUM(CASE WHEN STRFTIME('%w', v.date) NOT IN ('5', '6', '0') THEN 1 ELSE 0 END) AS weekday_visits,
    ROUND(
        SUM(CASE WHEN STRFTIME('%w', v.date) IN ('5', '6', '0') THEN 1.0 ELSE 0 END) / 
        SUM(CASE WHEN STRFTIME('%w', v.date) NOT IN ('5', '6', '0') THEN 1.0 ELSE 0 END), 2
    ) AS weekend_to_weekday_ratio
FROM shops s
JOIN visits v ON s.shop_id = v.shop_id
GROUP BY s.shop_type;


-- 20. High-Revenue Shops with Poor Ratings (Quality Intervention Candidates)
-- Business Value: Identifies high-revenue operations that might risk customer churn due to declining ratings.
SELECT 
    s.shop_id,
    s.shop_name,
    ROUND(SUM(srv.price), 2) AS total_revenue,
    s.rating AS avg_rating
FROM shops s
JOIN visits v ON s.shop_id = v.shop_id
JOIN services srv ON v.service_id = srv.service_id
GROUP BY s.shop_id, s.shop_name, s.rating
HAVING total_revenue > (
    SELECT AVG(revenue) FROM (
        SELECT SUM(s2.price) AS revenue FROM visits v2 JOIN services s2 ON v2.service_id = s2.service_id GROUP BY v2.shop_id
    )
) AND s.rating < 4.0
ORDER BY total_revenue DESC;
